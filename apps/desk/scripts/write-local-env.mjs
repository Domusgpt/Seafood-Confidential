#!/usr/bin/env node
// Write apps/desk/.env.local (the app) and apps/desk/.env.ops.local (operator scripts) from the
// running local Supabase stack. Both files are git-ignored and hold local-only values. The app's
// file never contains the Supabase secret key or the database owner URL.
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const desk = path.resolve(here, '..');
const root = path.resolve(desk, '../..');

const raw = execFileSync('pnpm', ['exec', 'supabase', 'status', '-o', 'json'], {
  cwd: root,
  encoding: 'utf8',
});
const status = JSON.parse(raw.slice(raw.indexOf('{')));
for (const key of ['API_URL', 'DB_URL', 'PUBLISHABLE_KEY', 'SECRET_KEY']) {
  if (!status[key]) throw new Error(`supabase status did not report ${key}; is the local stack running?`);
}

// Keep generated secrets stable across re-runs so existing sessions and hashes stay valid.
const previous = (file) =>
  existsSync(file)
    ? Object.fromEntries(
        readFileSync(file, 'utf8')
          .split('\n')
          .filter((l) => l && !l.startsWith('#') && l.includes('='))
          .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]),
      )
    : {};
const appFile = path.join(desk, '.env.local');
const opsFile = path.join(desk, '.env.ops.local');
const prev = previous(appFile);

const dbUrl = new URL(status.DB_URL);
const deskDbUrl = `postgresql://desk_app:desk_app_local_only@${dbUrl.host}${dbUrl.pathname}`;

const app = {
  DESK_SITE_URL: 'http://127.0.0.1:3000',
  SUPABASE_URL: status.API_URL,
  SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY,
  DESK_DATABASE_URL: deskDbUrl,
  INTAKE_HASH_SECRET: prev.INTAKE_HASH_SECRET ?? randomBytes(32).toString('base64url'),
  NEXT_SERVER_ACTIONS_ENCRYPTION_KEY:
    prev.NEXT_SERVER_ACTIONS_ENCRYPTION_KEY ?? randomBytes(32).toString('base64'),
  GHOST_ADMIN_URL: prev.GHOST_ADMIN_URL ?? 'http://localhost:2368',
  // Next.js fills X-Forwarded-For from the socket when absent; the test runner sets it per test.
  DESK_TRUSTED_PROXY_HOPS: prev.DESK_TRUSTED_PROXY_HOPS ?? '1',
  DESK_AGENT_RATE_PER_MINUTE: prev.DESK_AGENT_RATE_PER_MINUTE ?? '120',
  LOG_LEVEL: prev.LOG_LEVEL ?? 'info',
};
const ops = {
  SUPABASE_URL: status.API_URL,
  SUPABASE_SECRET_KEY: status.SECRET_KEY,
  SUPABASE_ADMIN_DB_URL: status.DB_URL,
  MAILPIT_URL: status.MAILPIT_URL ?? 'http://127.0.0.1:54324',
};

const render = (title, vars) =>
  `# ${title}\n# Generated by apps/desk/scripts/write-local-env.mjs from \`supabase status\`. Local only; never commit.\n` +
  Object.entries(vars)
    .map(([k, v]) => `${k}=${v}`)
    .join('\n') +
  '\n';
writeFileSync(appFile, render('Desk app environment (local)', app), { mode: 0o600 });
writeFileSync(opsFile, render('Operator scripts environment (local): holds the Supabase secret key', ops), {
  mode: 0o600,
});
console.log(`wrote ${path.relative(root, appFile)} and ${path.relative(root, opsFile)}`);
